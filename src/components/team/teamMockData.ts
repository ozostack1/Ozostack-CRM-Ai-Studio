export type EmploymentType = 'Full-Time' | 'Part-Time' | 'Contractor' | 'Intern';
export type MemberStatus = 'Active' | 'On Leave' | 'Remote' | 'Offline' | 'Probation';
export type DepartmentType = string;

export interface EmployeeMember {
  id: string;
  name: string;
  avatar: string;
  avatarBg?: string;
  email: string;
  phone: string;
  role: string;
  department: DepartmentType;
  employmentType: EmploymentType;
  status: MemberStatus;
  location: string;
  joinDate: string;
  manager: string;
  salary: number; // Annual in USD
  tasksDone: string;
  tasksDoneNum: number;
  totalTasks: number;
  productivity: number; // 0 - 100
  rating: number; // 1.0 - 5.0
  skills: string[];
  activeProjects: string[];
  attendanceRate: number; // %
  hoursLoggedThisMonth: number;
  leaveBalance: {
    vacation: number;
    sick: number;
    casual: number;
  };
  bio?: string;
  emergencyContact?: string;
}

export interface DepartmentSummary {
  id: string;
  name: DepartmentType;
  head: string;
  headAvatar: string;
  memberCount: number;
  openPositions: number;
  monthlyBudget: number;
  avgProductivity: number;
  description: string;
  color: string;
}

export interface AttendanceRecord {
  id: string;
  memberId: string;
  memberName: string;
  avatar: string;
  role: string;
  department: DepartmentType;
  date: string;
  checkIn: string;
  checkOut?: string;
  hoursWorked: number;
  status: 'Present' | 'Late' | 'Half Day' | 'On Leave' | 'Remote';
  overtimeHours?: number;
}

export interface LeaveRequest {
  id: string;
  memberId: string;
  memberName: string;
  avatar: string;
  role: string;
  department: DepartmentType;
  leaveType: 'Annual Vacation' | 'Sick Leave' | 'Casual Leave' | 'Parental Leave' | 'Unpaid';
  startDate: string;
  endDate: string;
  days: number;
  reason: string;
  status: 'Pending' | 'Approved' | 'Rejected';
  appliedOn: string;
  reviewedBy?: string;
}

export interface PerformanceReview {
  id: string;
  memberId: string;
  memberName: string;
  avatar: string;
  role: string;
  department: DepartmentType;
  reviewPeriod: string;
  rating: number;
  okrScore: number;
  reviewer: string;
  strengths: string[];
  goals: string[];
  feedback: string;
  date: string;
}

export interface JobRequisition {
  id: string;
  title: string;
  department: DepartmentType;
  type: EmploymentType;
  experienceLevel: string;
  salaryBand: string;
  openings: number;
  applicantsCount: number;
  stage: 'Sourcing' | 'Interviewing' | 'Final Review' | 'Offer Extended' | 'Closed';
  hiringManager: string;
  postedDate: string;
}

